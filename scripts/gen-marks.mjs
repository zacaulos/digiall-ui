// Extracts the brand SVG geometry from the committed logo files into a TS module.
// Regenerate with: node scripts/gen-marks.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const read = (f) => readFileSync(new URL(`../${f}`, import.meta.url), 'utf8')

const viewBoxOf = (svg) => svg.match(/viewBox="([^"]+)"/)[1]
const pathsOf = (svg) => [...svg.matchAll(/<path[^>]*\bd="([^"]+)"[^>]*>/g)].map((m) => ({
  d: m[1],
  transform: (m[0].match(/transform="([^"]+)"/) || [])[1] ?? null,
}))

const stacked = read('digiall-stacked.svg')
const horizontal = read('digiall-horizontal.svg')
const monogram = read('digiall-monogram.svg')

const [wordmark, descriptorStacked] = pathsOf(stacked)
const [, descriptorTop, descriptorBottom] = pathsOf(horizontal)
const [monogramD] = pathsOf(monogram)

// The teal dot on the D: same spot relative to the glyph in every lockup. The ring (gap) is
// knocked out of the D, so the dot reads on any background.
const dotOnWordmark = { cx: '78', cy: '9.6', r: '8', gap: '4.5' }

const marks = {
  wordmark: { viewBox: '0 0 485.90 68.60', paths: [wordmark], dot: dotOnWordmark },
  stacked: { viewBox: '0 0 485.90 118.18', paths: [wordmark, descriptorStacked], dot: dotOnWordmark },
  stackedRule: {
    viewBox: '0 0 485.90 131.35',
    dot: dotOnWordmark,
    paths: [wordmark, { ...descriptorStacked, transform: 'translate(0,131.35)' }],
    rects: [{ x: '0', y: '87.81', width: '485.90', height: '1.5', opacity: '.4' }],
  },
  horizontal: {
    viewBox: '0 0 650.55 68.60',
    paths: [wordmark, descriptorTop, descriptorBottom],
    dot: dotOnWordmark,
    rects: [{ x: '495.16', y: '16.19', width: '1.6', height: '36.21', opacity: '.38' }],
  },
  monogram: { viewBox: '0 0 153.40 153.40', paths: [monogramD], radius: '30.68', size: '153.40', dot: { cx: '108', cy: '52', r: '8', gap: '4.5' } },
}

const out = `// GENERATED by scripts/gen-marks.mjs — do not edit by hand.
// Source of truth: digiall-stacked.svg, digiall-horizontal.svg, digiall-monogram.svg
export interface MarkPath {
  d: string
  transform: string | null
}

export interface MarkRect {
  x: string
  y: string
  width: string
  height: string
  opacity: string
}

export interface MarkDot {
  cx: string
  cy: string
  r: string
  gap: string
}

export interface Mark {
  viewBox: string
  paths: MarkPath[]
  rects?: MarkRect[]
  radius?: string
  size?: string
  dot: MarkDot
}

export const MARKS = ${JSON.stringify(marks, null, 2)} as const satisfies Record<string, Mark>

export type MarkName = keyof typeof MARKS
`

writeFileSync(new URL('../src/components/Logo/marks.ts', import.meta.url), out)
console.log('wrote src/components/Logo/marks.ts')
